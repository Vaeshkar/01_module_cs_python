
# Exercise 1: For Loop with Continue and Break
list_of_15 = list(range(16))
print(list_of_15)

for num in list_of_15:
    if num % 3 == 0:
        continue
    elif num > 10:
        print(f"Got to number 10. Going to stop.")
        break
    else:
        print(f"The current number is: {num}")

